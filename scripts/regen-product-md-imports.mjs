#!/usr/bin/env node
/**
 * Regenerate src/utils/_productMdImports.ts
 * Imports only core reference sheets. FAQ content is generated into runtime
 * search indexes and model/language shards by build-faq-content.mjs.
 *
 * Output uses static imports with ?raw suffix (NOT import.meta.glob),
 * avoiding Vite 7 / Miaoda's unicode-path glob {} bug.
 */
import { readdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, resolve, dirname, basename, relative } from 'node:path';

const __dirname = dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Z]:)/, '$1');
const ROOT = resolve(__dirname, '..');
const PRODUCTS_DIR = join(ROOT, 'products');
const OUT = join(ROOT, 'src', 'utils', '_productMdImports.ts');

const rootFiles = readdirSync(PRODUCTS_DIR, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.toLowerCase().endsWith('.md'))
  .map((d) => d.name)
  .sort();

const allMd = rootFiles;

console.log(`Products root MDs: ${rootFiles.length}`);
console.log(`TOTAL: ${allMd.length}`);

const lines = [];
lines.push('// This file is AUTO-GENERATED by scripts/regen-product-md-imports.mjs');
lines.push('// Do NOT edit by hand. Regenerate with: node scripts/regen-product-md-imports.mjs');
lines.push('// Core reference sheets only; FAQ bodies load from generated static shards on demand.');
lines.push('// Static imports avoid the Vite glob path issues for CJK filenames.');
lines.push('');

const imports = [];
const recordEntries = [];

allMd.forEach((rel, i) => {
  const ident = `md_${i.toString().padStart(5, '0')}`;
  // _productMdImports.ts lives in src/utils/. From that location to repo-root /products/
  // is two levels up → ../../products/<rel>. The ?raw Vite suffix is part of the
  // quoted module specifier (Vite's ?raw transform + our custom resolver plugin
  // both expect it INSIDE the closing quote / path string).
  const importSpecifier = JSON.stringify(`../../products/${rel}?raw`);
  imports.push(`import ${ident} from ${importSpecifier};`);
  // In-memory record key uses the bare relative path (no ../ prefix, no ?raw)
  // because productData.ts indexes ALL_PRODUCT_MD with the stable sheet/file
  // name as it was produced by the FAQ converter.
  recordEntries.push(`  ${JSON.stringify(rel)}: ${ident}`);
});

lines.push(...imports);
lines.push('');
lines.push('export const ALL_PRODUCT_MD: Record<string, string> = {');
lines.push(recordEntries.join(',\n'));
lines.push('};');
lines.push('');

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`\n✅ Written: ${relative(ROOT, OUT)}  (${lines.length} lines)`);
