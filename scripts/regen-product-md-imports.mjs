#!/usr/bin/env node
/**
 * Regenerate src/utils/_productMdImports.ts
 * Combines:
 *   (a) original /products/*.md (comparison tables, specs, errors, etc.)
 *   (b) /products/FAQ/*.md (Q&A + comparison tables — new FAQ data)
 *
 * Output uses static imports with ?raw suffix (NOT import.meta.glob),
 * avoiding Vite 7 / Miaoda's unicode-path glob {} bug.
 */
import { readdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, resolve, dirname, basename, relative } from 'node:path';

const __dirname = dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Z]:)/, '$1');
const ROOT = resolve(__dirname, '..');
const PRODUCTS_DIR = join(ROOT, 'products');
const FAQ_DIR = join(PRODUCTS_DIR, 'FAQ');
const OUT = join(ROOT, 'src', 'utils', '_productMdImports.ts');

const rootFiles = readdirSync(PRODUCTS_DIR, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.toLowerCase().endsWith('.md'))
  .map((d) => d.name)
  .sort();

const faqFiles = readdirSync(FAQ_DIR, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.toLowerCase().endsWith('.md'))
  .map((d) => `FAQ/${d.name}`)
  .sort();

const allMd = [...rootFiles, ...faqFiles];

console.log(`Products root MDs: ${rootFiles.length}`);
console.log(`FAQ MDs: ${faqFiles.length}`);
console.log(`TOTAL: ${allMd.length}`);

const lines = [];
lines.push('// This file is AUTO-GENERATED by scripts/regen-product-md-imports.mjs');
lines.push('// Do NOT edit by hand. Regenerate with: node scripts/regen-product-md-imports.mjs');
lines.push('// We use static ?raw imports instead of import.meta.glob() because Vite 7 + Miaoda');
lines.push('// returns {} for paths that contain CJK characters, spaces or parentheses.');
lines.push('');

const imports = [];
const recordEntries = [];

allMd.forEach((rel, i) => {
  const ident = `md_${i.toString().padStart(5, '0')}`;
  const escaped = JSON.stringify(`../products/${rel}`);
  imports.push(`import ${ident} from ${escaped}?raw;`);
  recordEntries.push(`  ${JSON.stringify(rel)}: ${ident}`);
});

lines.push(...imports);
lines.push('');
lines.push('export const ALL_PRODUCT_MD: Record<string, string> = {');
lines.push(recordEntries.join(',\n'));
lines.push('};');
lines.push('');

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`\n✅ Written: ${relative(ROOT, OUT)}  (${lines.length} lines)`);
