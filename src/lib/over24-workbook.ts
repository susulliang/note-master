import * as XLSX from 'xlsx';
import type { ReportCaseRecord } from '@/hooks/use-ccp-extension-bridge';

/**
 * Parses the Salesforce "Over 24H" report xlsx export (Printable View
 * layout): rows of metadata (title / "As of" / filters), then a header row
 * containing "Case Number", then one row per case.
 *
 * Recognized columns (by exact trimmed header text):
 *   Case Number · Case Owner · Case Last Modified By ·
 *   Case Last Modified Date · Status · Customer Last Reply Time ·
 *   Hours Since Last Customer Reply
 *
 * Returns one ReportCaseRecord per case row (rows without a numeric case
 * number are skipped), plus the report's "As of" timestamp when present.
 */
export function parseOver24Workbook(
  data: ArrayBuffer,
  fileName: string
): { cases: ReportCaseRecord[]; asOf: string | null; totalRows: number } {
  const wb = XLSX.read(data, { type: 'array' });
  const sheet = wb.Sheets[wb.SheetNames[0]];
  if (!sheet) throw new Error(`${fileName}: no sheets found`);

  const rows = XLSX.utils.sheet_to_json<string[]>(sheet, {
    header: 1,
    raw: false,
    defval: '',
  });
  if (rows.length === 0) throw new Error(`${fileName}: sheet is empty`);

  // Report "As of ..." line (row index 2 in the standard export layout).
  const asOf = rows
    .slice(0, 5)
    .map((r) => r.find((c) => /^\s*As of\s+/i.test(String(c)) || /Generated by/i.test(String(c))))
    .find(Boolean)
    ?.trim() ?? null;

  // Locate the header row (any cell trimmed === "Case Number").
  const headerIdx = rows.findIndex((r) =>
    r.some((c) => String(c).trim().toLowerCase() === 'case number')
  );
  if (headerIdx === -1) throw new Error(`${fileName}: "Case Number" header row not found`);

  const col = (name: RegExp): number =>
    rows[headerIdx]!.findIndex((c) => name.test(String(c).trim()));
  const cNumber = col(/^case number$/i);
  const cOwner = col(/^case owner$/i);
  const cModified = col(/^case last modified date$/i);
  const cStatus = col(/^status$/i);
  const cLastReply = col(/^customer last reply time$/i);
  if (cNumber === -1) throw new Error(`${fileName}: Case Number column missing`);

  const cases: ReportCaseRecord[] = [];
  for (let i = headerIdx + 1; i < rows.length; i++) {
    const row = rows[i]!;
    const caseNumber = String(row[cNumber] ?? '').trim();
    if (!/\d{5,}/.test(caseNumber)) continue; // blank / footer rows
    cases.push({
      caseNumber,
      caseOwner: cOwner !== -1 ? String(row[cOwner] ?? '').trim() || null : null,
      lastModifiedDate: cModified !== -1 ? String(row[cModified] ?? '').trim() || null : null,
      status: cStatus !== -1 ? String(row[cStatus] ?? '').trim() || null : null,
      customerLastReplyTime: cLastReply !== -1 ? String(row[cLastReply] ?? '').trim() || null : null,
    });
  }

  return { cases, asOf, totalRows: rows.length };
}
