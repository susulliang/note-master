function Translate-Text {
    param([string]$text)
    if ([string]::IsNullOrEmpty($text)) { return "" }
    $result = $text
    $sortedKeys = $dict.Keys | Sort-Object Length -Descending
    foreach ($key in $sortedKeys) {
        $result = $result -replace [regex]::Escape($key), $dict[$key]
    }
    return $result
}

# Process GOAT error codes
$goatFiles = Get-ChildItem $goatDir -Filter "*.md" | Where-Object { $_.Name -ne "001_GOAT_Error_Codes_INDEX.md" }
$goatCount = 0
foreach ($file in $goatFiles) {
    $content = Get-Content $file -Raw
    $translated = Translate-Text $content
    $translated | Out-File -FilePath $file.FullName -Encoding UTF8
    $goatCount++
}
Write-Host ("Translated $goatCount GOAT error code files")

